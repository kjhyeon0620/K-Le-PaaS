-- #117 AI diagnosis history. New table; the previous release neither reads nor writes it.
create table deployment_diagnoses (
    id bigint generated by default as identity,
    deployment_id bigint not null,
    requested_model varchar(100) not null,
    prompt_version varchar(50) not null,
    result text not null,
    input_tokens bigint,
    cached_input_tokens bigint,
    output_tokens bigint,
    reasoning_tokens bigint,
    latency_ms bigint,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);
alter table deployment_diagnoses add constraint fk_deployment_diagnoses_deployment
    foreign key (deployment_id) references deployments;
create index idx_deployment_diagnoses_deployment on deployment_diagnoses (deployment_id, id desc);
