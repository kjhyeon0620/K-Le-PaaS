-- #104 RAG diagnosis knowledge: app documents, confirmed incidents, and embedded chunks.
-- New tables only; the previous release neither reads nor writes them.
create table knowledge_documents (
    id bigint generated by default as identity,
    repository_id bigint not null,
    slug varchar(64) not null,
    title varchar(200) not null,
    content text not null,
    revision integer not null,
    updated_by_user_id bigint,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_knowledge_documents_repository_slug unique (repository_id, slug)
);
alter table knowledge_documents add constraint fk_knowledge_documents_repository
    foreign key (repository_id) references repositories;

create table incidents (
    id bigint generated by default as identity,
    deployment_id bigint not null,
    repository_id bigint not null,
    category varchar(32) not null,
    root_cause varchar(64) not null,
    resolution text,
    confirmed_by_user_id bigint,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_incidents_deployment unique (deployment_id)
);
alter table incidents add constraint fk_incidents_deployment foreign key (deployment_id) references deployments;
alter table incidents add constraint fk_incidents_repository foreign key (repository_id) references repositories;

-- repository_id null = platform runbook shared by every app
create table knowledge_chunks (
    id bigint generated by default as identity,
    repository_id bigint,
    deployment_id bigint,
    source_type varchar(16) not null,
    source_ref varchar(200) not null,
    source_title varchar(200) not null,
    source_version varchar(200),
    source_updated_at timestamp(6),
    chunk_index integer not null,
    text text not null,
    embedding bytea not null,
    embedding_model varchar(100) not null,
    content_hash varchar(64) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);
alter table knowledge_chunks add constraint fk_knowledge_chunks_repository foreign key (repository_id) references repositories;
create index idx_knowledge_chunks_repository on knowledge_chunks (repository_id);
create index idx_knowledge_chunks_source on knowledge_chunks (source_ref);
