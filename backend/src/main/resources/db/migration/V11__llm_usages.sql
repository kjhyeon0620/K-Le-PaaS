-- #176 LLM usage ledger (one row per model call) for per-user daily cost budget. New table; the previous release neither reads nor writes it.
create table llm_usages (
    id bigint generated by default as identity,
    user_id bigint not null,
    feature varchar(20) not null,
    provider varchar(30) not null,
    model varchar(100) not null,
    outcome varchar(10) not null,
    input_tokens bigint,
    cached_input_tokens bigint,
    output_tokens bigint,
    reasoning_tokens bigint,
    cost_usd numeric(12, 6),
    latency_ms bigint,
    deployment_id bigint,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);
alter table llm_usages add constraint fk_llm_usages_user foreign key (user_id) references users;
create index idx_llm_usages_user_created on llm_usages (user_id, created_at);
